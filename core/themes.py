def is_winter_season(today: date | None = None) -> bool:
    """Meteorological winter on the user's computer: December, January, February."""
    today = today or date.today()
    return today.month in {12, 1, 2}


def is_theme_available(theme_key: str, today: date | None = None) -> bool:
    theme = THEMES.get(theme_key)
    if not theme:
        return False
    if not is_theme_visible(theme_key, today):
        return False
    if is_theme_secret(theme_key) and not has_mark(theme_key):
        return False
    return True


def is_theme_secret(theme_key: str) -> bool:
    return theme_key in marked_names()


def is_theme_visible(theme_key: str, today: date | None = None) -> bool:
    theme = THEMES.get(theme_key)
    if not theme:
        return False
    if theme.get("available_season") == "winter":
        return is_winter_season(today)
    return True


def visible_theme_keys(today: date | None = None) -> list[str]:
    return [theme_key for theme_key in THEMES if is_theme_visible(theme_key, today)]


def normalize_theme_key(theme_key: str | None) -> str:
    if theme_key in THEMES:
        return theme_key if is_theme_available(theme_key) else DEFAULT_THEME
    if isinstance(theme_key, str):
        normalized = theme_key.strip().lower().replace(" ", "_")
        resolved = THEME_ALIASES.get(normalized, DEFAULT_THEME)
        return resolved if is_theme_available(resolved) else DEFAULT_THEME
    return DEFAULT_THEME


P: dict[str, str] = dict(THEMES[DEFAULT_THEME])


def apply_theme(theme_key: str):
    global P
    theme_key = normalize_theme_key(theme_key)
    P.clear()
    P.update(THEMES[theme_key])
    from PyQt6.QtWidgets import QApplication
    from core.design_tokens import ui_font
    if QApplication.instance() is not None:
        QApplication.instance().setFont(ui_font())
    return theme_key
